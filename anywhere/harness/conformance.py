def run_platform(platform: str, cfgdir: Path, releases: Path | None, params: dict,
                 node_filter: str | None, dry_run: bool, run_dir: Path,
                 arch_override: str | None = None) -> dict:
    section = params.get("_sections", {}).get(platform, {})
    arch, arch_problem = resolve_arch(platform, section, arch_override)
    if arch_problem:
        raise SystemExit(arch_problem)
    # distinguish arches of the same platform in reports and results.json
    label = (f"{platform}-{arch}"
             if arch and len(RELEASE_ARTIFACT_KEY.get(platform, {})) > 1
             else platform)
    template = load_platform_config(cfgdir, platform)

    binary, problem = None, None
    if not dry_run:
        binary, problem = resolve_binary(platform, section, releases, run_dir, arch)
        if binary is None:
            raise SystemExit(problem or
                             f"[{platform}] no binary: set [{platform}] file= in test.toml or pass -r")

    nodes = load_nodes(cfgdir)
    if node_filter:
        wanted = {t.strip() for t in node_filter.split(",") if t.strip()}
        nodes = [n for n in nodes if n.get("tag", "unnamed") in wanted]
        if not nodes:
            raise SystemExit(f"no node matching {node_filter!r} in outbounds.toml")

    runner = None
    bin_tgz = None
    binary = None
    if not dry_run:
        bin_tgz = stage_binary_tgz(platform, binary, run_dir) if platform != "mac" else None
        ui_tgz = resolve_ui_tgz(releases) if platform in ("windows", "linux") else None
        serve_path = None
        if platform in ("windows", "linux"):
            # deploy dir comes from the platform's own serve_path; if the
            # platform file did not override it, the value is still the
            # template placeholder -> treat as unconfigured
            merged = template.get("ui", {}).get("serve_path")
            raw = load_template(cfgdir).get("ui", {}).get("serve_path")
            if merged and merged != raw:
                serve_path = merged
        runner = make_runner(platform, section, binary, run_dir,
                             bin_tgz=bin_tgz, ui_tgz=ui_tgz, serve_path=serve_path)
        runner.setup()

    results: list[NodeResult] = []
    logs: dict[str, str] = {}
    try:
        for node in nodes:
            tag = node.get("tag", "unnamed")
            if node["type"] in NON_TESTABLE_TYPES:
                results.append(NodeResult(tag=tag, type=node["type"], server=None, skipped=True))
                print(f"[{label}] {tag:<14} skipped ({node['type']})")
                continue
            text, _ = assemble(template, node)
            if dry_run:
                out = run_dir / f"final-{tag}.toml"
                out.write_text(text)
                print(f"[{label}] {tag:<14} dry-run -> {out}")
                continue
            print(f"[{label}] {tag:<14} ({node['type']}) testing ...", flush=True)
            res = test_node(runner, node, template, params, run_dir)
            ratio = params["pass_ratio"]
            res.pass_ = all(s.passed(ratio) for s in res.sites) if res.sites else None
            if res.error and not res.sites:
                res.pass_ = False
            results.append(res)
            p50s = [round(statistics.median(s.latencies) * 1000) for s in res.sites if s.latencies]
            verdict = "PASS" if res.pass_ else "FAIL"
            msg = (f"[{label}] {tag:<14} {verdict}"
                   + (f" first={res.first_ms}ms" if res.first_ms is not None else "")
                   + (f" p50={min(p50s)}-{max(p50s)}ms" if p50s else "")
                   + (f" err={res.error}" if res.error else ""))
            print(msg, flush=True)
    finally:
        if runner is not None:
            runner.cleanup()
        # keep run dirs to configs/logs/results only: the staged tgz and
        # the extracted-binary dir are dead weight once the run is over
        if bin_tgz is not None:
            bin_tgz.unlink(missing_ok=True)
            if binary is not None:
                bdir = binary.parent.resolve()
                root = (run_dir / f"bin-{platform}").resolve()
                if str(bdir).startswith(str(root)):
                    shutil.rmtree(root, ignore_errors=True)

    for r in results:
        if r.error:
            logp = run_dir / f"client-{r.tag}.log"
            if logp.exists():
                # cmd.exe on localized windows emits GBK, not UTF-8
                enc = "gbk" if platform == "windows" else "utf-8"
                logs.setdefault(r.tag, logp.read_text(encoding=enc, errors="replace"))

    return {
        "platform": label,
        "binary": str(binary) if binary else None,
        "nodes": [r.summary(params["pass_ratio"]) for r in results],
        "logs": logs,
    }


def run_self(platform: str, cfgdir: Path, releases: Path | None, params: dict,
             dry_run: bool, run_dir: Path) -> dict:
    """Self-loopback section: anywhere on this platform talking to itself.
    For each inbound in inbounds.toml: assemble a single-inbound server
    config + the paired client outbound, start the server as a background
    process on the device, then run the same G/Y/X probes through it.
    A failure here points at the inbound (server-side) implementation,
    since the client side is covered by the real-node matrix."""
    section = params.get("_sections", {}).get(platform, {})
    template = load_platform_config(cfgdir, platform)
    server_tpl_text = (cfgdir / "server.toml").read_text()
    if "##test inbound##" not in server_tpl_text:
        raise SystemExit(f"{cfgdir / 'server.toml'} has no `##test inbound##` placeholder")
    server_tpl = tomllib.loads(server_tpl_text)
    inbounds = load_inbound_pool(cfgdir)
    if not inbounds:
        raise SystemExit(f"{cfgdir / 'inbounds.toml'} has no [[inbounds]] blocks")

    binary, problem = None, None
    if dry_run:
        runner = None
    else:
        binary, problem = resolve_binary(platform, section, releases, run_dir, None)
        if binary is None:
            raise SystemExit(problem or f"[{platform}] no binary for self test")
        runner = make_runner(platform, section, binary, run_dir)
        runner.setup()
        # self-signed cert lives next to the server config (anywhere resolves
        # relative cert paths against the config file's directory)
        gen_self_cert(run_dir)

    results: list[NodeResult] = []
    logs: dict[str, str] = {}
    try:
        for inbound in inbounds:
            tag = self_tag(inbound)
            uuid = str(uuid4())
            server_text, client_text, _ = assemble_self(server_tpl, template,
                                                        inbound, uuid)
            if dry_run:
                (run_dir / f"self-server-{tag.replace(':', '_')}.toml").write_text(server_text)
                (run_dir / f"final-{tag.replace(':', '_')}.toml").write_text(client_text)
                print(f"[{platform}] {tag:<20} dry-run (self)")
                continue
            listen = inbound["listen"]
            in_port = int(listen.rsplit(":", 1)[1])
            if runner is None:
                continue
            print(f"[{platform}] {tag:<20} ({inbound['type']}) self testing ...",
                  flush=True)
            res = NodeResult(tag=tag, type=inbound["type"], server=listen)
            err = runner.start_bg(server_text, f"server-{tag.replace(':', '_')}")
            if err:
                res.error = err
                res.pass_ = False
                results.append(res)
                print(f"[{platform}] {tag:<20} FAIL err={err}", flush=True)
                continue
            try:
                # server readiness: probe the inbound port through the same
                # channel the client will use (mac: localhost; remote:
                # forwarded socks covers it via warmup retry instead)
                if platform == "mac":
                    if not wait_port(in_port, timeout=10):
                        res.error = f"server inbound {listen} never came up"
                        res.pass_ = False
                        results.append(res)
                        print(f"[{platform}] {tag:<20} FAIL err={res.error}",
                              flush=True)
                        continue
                port, proc, log_path = runner.start(client_text, tag)
                connect_timeout = params["connect_timeout_s"]
                probe_timeout = params["probe_timeout_s"]
                sites = [SiteStats(url=u) for u in params.get("self_sites")
                         or params["sites"]]
                res.sites = sites
                werr = runner.wait_ready(port, proc, log_path)
                if werr:
                    res.error = werr
                    res.pass_ = False
                else:
                    deadline = time.monotonic() + 20
                    while True:
                        ok, code, lat, werr2 = curl_once(port, sites[0].url,
                                                         connect_timeout, probe_timeout)
                        if ok:
                            res.first_ms = round(lat * 1000)
                            break
                        sites[0].error = werr2 or f"http {code}"
                        if time.monotonic() > deadline:
                            res.error = f"warmup failed: {sites[0].error}"
                            res.pass_ = False
                            break
                        time.sleep(0.5)
                    if res.pass_ is not False:
                        err = run_probes(port, sites, params, poll_proc=proc.poll)
                        if err:
                            res.error = err
                runner.stop(proc)
            finally:
                if runner.bg_proc is not None:
                    _stop_proc(runner.bg_proc)
                    runner.bg_proc = None
            ratio = params["pass_ratio"]
            if res.pass_ is None:
                res.pass_ = bool(res.sites) and all(s.passed(ratio) for s in res.sites)
            results.append(res)
            p50s = [round(statistics.median(s.latencies) * 1000) for s in res.sites if s.latencies]
            totals = [f"{s.ok}/{s.total}" for s in res.sites]
            msg = (f"[{platform}] {tag:<20} {'PASS' if res.pass_ else 'FAIL'}"
                   + (f" first={res.first_ms}ms" if res.first_ms else "")
                   + f" totals={totals}"
                   + (f" p50={min(p50s)}-{max(p50s)}ms" if p50s else "")
                   + (f" err={res.error}" if res.error else ""))
            print(msg, flush=True)
    finally:
        if runner is not None:
            runner.cleanup()

    for r in results:
        if r.error:
            logp = run_dir / f"client-{r.tag.replace(':', '_')}.log"
            if logp.exists():
                enc = "gbk" if platform == "windows" else "utf-8"
                logs.setdefault(r.tag, logp.read_text(encoding=enc, errors="replace"))

    return {
        "platform": f"{platform}-self",
        "binary": str(binary) if binary else None,
        "nodes": [r.summary(params["pass_ratio"]) for r in results],
        "logs": logs,
    }


