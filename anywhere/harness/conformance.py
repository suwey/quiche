def _site_cell(s: dict) -> str:
    if s["total"] == 0:
        return '<td class="fail">—</td>'
    if s["pass"]:
        return f'<td class="pass">✓ {s["ok"]}/{s["total"]} · {s["p50_ms"]}ms</td>'
    return f'<td class="fail">✗ {s["ok"]}/{s["total"]}</td>'


SITE_COLORS = ["#4e79a7", "#f28e2b", "#59a14f", "#e15759", "#b07aa1", "#76b7b2"]


def _svg_bars(platform_results: list[dict], params: dict) -> str:
    """Grouped bar chart: one cluster per site, one bar per node (p50 ms).
    Site clusters are derived from the nodes' own data (the self section
    probes a different, single direct-reachable site)."""
    entries = []  # (chart label, {url: p50 or None}, set of tested urls)
    urls: list[str] = []
    for pr in platform_results:
        for n in pr["nodes"]:
            if n["skipped"]:
                continue
            per = {}
            for s in n["sites"]:
                per[s["url"]] = s.get("p50_ms")
                if s["url"] not in urls:
                    urls.append(s["url"])
            entries.append((f"{pr['platform']}·{n['tag']}", per))
    if not entries:
        return "<p>no data</p>"
    bar_w, gap, group_gap = 26, 6, 40
    n_sites = len(urls)
    group_w = len(entries) * bar_w + (len(entries) - 1) * gap
    width = 44 + n_sites * (group_w + group_gap)
    height, top, bottom = 210, 26, 48
    max_ms = max((p for _, per in entries for p in per.values() if p), default=100)
    max_ms = max(max_ms, 100)
    scale = (height - top - bottom) / max_ms
    baseline = height - bottom
    parts = [f'<svg width="{width}" height="{height}" '
             f'xmlns="http://www.w3.org/2000/svg" font-family="sans-serif">']
    for frac in (0, 0.25, 0.5, 0.75, 1.0):
        y = baseline - frac * (height - top - bottom)
        parts.append(f'<line x1="42" x2="{width - 6}" y1="{y:.0f}" y2="{y:.0f}" '
                     f'stroke="#eee"/>')
        parts.append(f'<text x="38" y="{y + 4:.0f}" text-anchor="end" '
                     f'font-size="10" fill="#888">{round(max_ms * frac)}</text>')
    for si, site in enumerate(urls):
        gx = 44 + si * (group_w + group_gap)
        for ni, (label, per) in enumerate(entries):
            p50 = per.get(site)
            tested = site in per
            x = gx + ni * (bar_w + gap)
            color = SITE_COLORS[ni % len(SITE_COLORS)]
            if p50:
                bh = p50 * scale
                parts.append(f'<rect x="{x}" y="{baseline - bh:.0f}" width="{bar_w}" '
                             f'height="{bh:.0f}" fill="{color}" rx="2">'
                             f'<title>{html.escape(label)} · {html.escape(site_label(site))}'
                             f': {p50}ms</title></rect>')
                parts.append(f'<text x="{x + bar_w / 2}" y="{baseline - bh - 5:.0f}" '
                             f'text-anchor="middle" font-size="9" fill="#444">{p50}</text>')
            elif tested:  # probed but never succeeded
                parts.append(f'<text x="{x + bar_w / 2}" y="{baseline - 5:.0f}" '
                             f'text-anchor="middle" font-size="12" fill="#c0272d">✕</text>')
            # else: this node never probes this site (other section) — no mark
        parts.append(f'<text x="{gx + group_w / 2}" y="{height - 30}" text-anchor="middle" '
                     f'font-size="11" fill="#333">{html.escape(site_label(site))}</text>')
    # per-node polyline connecting its bar tops across the site groups —
    # white halo first so the line stays visible on top of same-color bars
    for ni, (label, per) in enumerate(entries):
        color = SITE_COLORS[ni % len(SITE_COLORS)]
        pts = []
        for si, site in enumerate(urls):
            p50 = per.get(site)
            if not p50:
                continue
            gx = 44 + si * (group_w + group_gap)
            x = gx + ni * (bar_w + gap) + bar_w / 2
            pts.append(f"{x:.0f},{baseline - p50 * scale:.0f}")
        if len(pts) >= 2:
            parts.append(f'<polyline points="{" ".join(pts)}" fill="none" stroke="#fff" '
                         f'stroke-width="4" stroke-linejoin="round" '
                         f'stroke-linecap="round" opacity="0.85"/>')
            parts.append(f'<polyline points="{" ".join(pts)}" fill="none" '
                         f'stroke="{color}" stroke-width="2" stroke-linejoin="round" '
                         f'stroke-linecap="round"/>')
    lx = 44
    for ni, (label, _) in enumerate(entries):
        color = SITE_COLORS[ni % len(SITE_COLORS)]
        parts.append(f'<rect x="{lx}" y="{height - 14}" width="9" height="9" '
                     f'fill="{color}"/>')
        parts.append(f'<text x="{lx + 13}" y="{height - 6}" font-size="10" '
                     f'fill="#333">{html.escape(label)}</text>')
        lx += 18 + 7 * len(label)
    parts.append("</svg>")
    return "".join(parts)


def _svg_timeline(node: dict, params: dict) -> str:
    """Per-node probe timeline: one colored polyline per site (that site's
    probes in order), failed probes as red ✕ on the baseline. X positions
    derive from each series' own length (count or duration mode)."""
    width, height, top, bottom, left = 620, 130, 14, 22, 46
    inner_w = width - left - 14
    inner_h = height - top - bottom
    baseline = height - bottom
    max_ms = max((m for s in node["sites"]
                  for ok, m in s.get("series", []) if ok and m), default=0)
    max_ms = max(max_ms, 500)
    scale = inner_h / max_ms
    parts = [f'<svg width="{width}" height="{height}" '
             f'xmlns="http://www.w3.org/2000/svg" font-family="sans-serif">']
    for frac in (0, 0.5, 1.0):
        y = baseline - frac * inner_h
        parts.append(f'<line x1="{left}" x2="{width - 10}" y1="{y:.0f}" y2="{y:.0f}" '
                     f'stroke="#eee"/>')
        parts.append(f'<text x="{left - 4}" y="{y + 4:.0f}" text-anchor="end" '
                     f'font-size="10" fill="#888">{round(max_ms * frac)}</text>')
    for si, s in enumerate(node["sites"]):
        color = SITE_COLORS[si % len(SITE_COLORS)]
        name = html.escape(site_label(s["url"]))
        series = s.get("series", [])
        span = max(1, len(series) - 1)
        pts, fails = [], []
        for idx, (ok, ms) in enumerate(series):
            x = left + (inner_w / span) * idx
            if ok and ms:
                pts.append(f"{x:.0f},{baseline - ms * scale:.0f}")
            else:
                fails.append(x)
        if len(pts) >= 2:
            parts.append(f'<polyline points="{" ".join(pts)}" fill="none" '
                         f'stroke="{color}" stroke-width="2"/>')
        for p in pts:  # dots so single-success series stay visible
            x, y = p.split(",")
            parts.append(f'<circle cx="{x}" cy="{y}" r="3" fill="{color}"/>')
        for x in fails:
            parts.append(f'<text x="{x:.0f}" y="{baseline + 4}" text-anchor="middle" '
                         f'font-size="11" fill="#c0272d">✕</text>')
        parts.append(f'<circle cx="{left + 6 + si * 110}" cy="10" r="4" fill="{color}"/>')
        parts.append(f'<text x="{left + 15 + si * 110}" y="14" font-size="10" '
                     f'fill="#333">{name}</text>')
    parts.append("</svg>")
    return "".join(parts)


