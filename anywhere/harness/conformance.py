def probe_plan(params: dict) -> tuple[str, int, float | None]:
    """Resolve the sampling plan: (mode, fixed count, duration seconds).
    duration_s > 0 wins over count; count mode has no total-time cap."""
    duration = params.get("duration_s") or 0
    if duration > 0:
        return "duration", 0, float(duration)
    return "count", int(params["count"]), None


def run_probes(port: int, sites: list[SiteStats], params: dict,
               poll_proc) -> str | None:
    """Shared sampling loop (count mode: fixed probes per site; duration
    mode: probe at interval_ms until duration_s elapsed). Returns an error
    string when the client died mid-sampling, else None."""
    mode, count, duration = probe_plan(params)
    connect_timeout = params["connect_timeout_s"]
    probe_timeout = params["probe_timeout_s"]
    interval = params["interval_ms"] / 1000
    if mode == "duration":
        start = time.monotonic()
        i = 0
        while True:
            now = time.monotonic()
            if now - start >= duration:
                break
            st = sites[i % len(sites)]
            i += 1
            ok, code, lat, err = curl_once(port, st.url, connect_timeout, probe_timeout)
            st.total += 1
            st.series.append((ok, lat))
            if ok:
                st.ok += 1
                st.latencies.append(lat)
            elif st.error is None:
                st.error = err or f"http {code}"
            if poll_proc() is not None:
                return f"client exited mid-test (code {poll_proc()})"
            remaining = duration - (time.monotonic() - start)
            if remaining > interval:
                time.sleep(min(interval, remaining))
        return None
    probes = count * len(sites)
    for i in range(probes):
        st = sites[i % len(sites)]
        ok, code, lat, err = curl_once(port, st.url, connect_timeout, probe_timeout)
        st.total += 1
        st.series.append((ok, lat))
        if ok:
            st.ok += 1
            st.latencies.append(lat)
        elif st.error is None:
            st.error = err or f"http {code}"
        if poll_proc() is not None:
            return f"client exited mid-test (code {poll_proc()})"
        if i < probes - 1:
            time.sleep(interval)
    return None


# ---------------------------------------------------------------------------
# Minimal TOML emitter (stdlib has no writer). Supports exactly the shapes
# anywhere's configs use: scalars, arrays of scalars, tables, arrays of
# tables, arbitrarily nested. Every emitted document is round-trip checked
# against the source dict by the caller, so an emitter bug aborts loudly
# instead of producing a subtly wrong config.
# ---------------------------------------------------------------------------

_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")


def _key(k: str) -> str:
    if _BARE_KEY.match(k):
        return k
    escaped = k.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _scalar(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        escaped = (
            v.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        return f'"{escaped}"'
    if isinstance(v, (int, float)):
        return str(v)
    raise TypeError(f"unsupported TOML scalar: {v!r}")


def _emit_block(path: str, data: dict, out: list[str]) -> None:
    """Body of a table at dotted `path`; its header was already emitted.

    TOML requires a table's plain keys before its sub-tables, so scalars are
    written first regardless of dict order.
    """
    scalars, tables = [], []
    for k, v in data.items():
        if isinstance(v, (str, bool, int, float)):
            scalars.append((k, v))
        elif isinstance(v, list) and all(isinstance(x, (str, bool, int, float)) for x in v):
            scalars.append((k, v))
        else:
            tables.append((k, v))
    for k, v in scalars:
        if isinstance(v, list):
            out.append(f"{_key(k)} = [{', '.join(_scalar(x) for x in v)}]")
        else:
            out.append(f"{_key(k)} = {_scalar(v)}")
    for k, v in tables:
        kp = f"{path}.{k}" if path else k
        if isinstance(v, dict):
            out.append(f"[{kp}]")
            _emit_block(kp, v, out)
        elif isinstance(v, list):
            if not all(isinstance(x, dict) for x in v):
                raise TypeError(f"mixed list not supported at {kp}: {v!r}")
            for elem in v:
                out.append(f"[[{kp}]]")
                _emit_block(kp, elem, out)
        else:
            raise TypeError(f"unsupported TOML value at {kp}: {v!r}")


def toml_dumps(data: dict) -> str:
    scalars, tables = [], []
    for k, v in data.items():
        if isinstance(v, (str, bool, int, float)):
            scalars.append((k, v))
        elif isinstance(v, list) and all(isinstance(x, (str, bool, int, float)) for x in v):
            scalars.append((k, v))
        elif isinstance(v, (dict, list)):
            tables.append((k, v))
        else:
            raise TypeError(f"unsupported TOML value at root.{k}: {v!r}")
    out: list[str] = []
    for k, v in scalars:
        if isinstance(v, list):
            out.append(f"{_key(k)} = [{', '.join(_scalar(x) for x in v)}]")
        else:
            out.append(f"{_key(k)} = {_scalar(v)}")
    for k, v in tables:
        if isinstance(v, dict):
            out.append(f"[{_key(k)}]")
            _emit_block(k, v, out)
        else:
            for elem in v:
                out.append(f"[[{_key(k)}]]")
                _emit_block(k, elem, out)
    return "\n".join(out) + "\n"


