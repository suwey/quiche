def deep_merge(base: dict, override: dict) -> dict:
    """Tables merge recursively; arrays and scalars replace wholesale."""
    for k, v in override.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            deep_merge(base[k], v)
        else:
            base[k] = v
    return base


def load_template(cfgdir: Path) -> dict:
    text = (cfgdir / "config.toml").read_text()
    if PLACEHOLDER not in text:
        raise SystemExit(f"{cfgdir / 'config.toml'} has no `{PLACEHOLDER}` placeholder line — "
                         "not a conformance template?")
    return tomllib.loads(text)


def load_platform_config(cfgdir: Path, platform: str) -> dict:
    """Template, deep-merged with <platform>.toml when present and non-empty."""
    cfg = load_template(cfgdir)
    pf = cfgdir / f"{platform}.toml"
    if pf.exists() and pf.stat().st_size > 0:
        deep_merge(cfg, tomllib.loads(pf.read_text()))
    return cfg


def load_nodes(cfgdir: Path) -> list[dict]:
    doc = tomllib.loads((cfgdir / "outbounds.toml").read_text())
    return doc.get("outbounds", [])


def assemble(template: dict, node: dict) -> tuple[str, str]:
    """Inject `node` as tag "test" into the template; return (toml text,
    original tag). Round-trip checked so an emitter bug cannot silently
    produce a different config."""
    # The `##test node##` line in the template is a TOML comment and
    # disappears on parse; injection is positional (first outbound), which
    # the template's urltest group resolves by tag anyway.
    cfg = copy.deepcopy(template)
    original_tag = node.get("tag", "unnamed")
    injected = copy.deepcopy(node)
    injected["tag"] = TEST_TAG
    cfg.setdefault("outbounds", [])
    cfg["outbounds"].insert(0, injected)
    text = toml_dumps(cfg)
    if tomllib.loads(text) != cfg:
        raise RuntimeError(f"toml round-trip mismatch for node {original_tag}")
    return text, original_tag


def socks_port(assembled: str) -> int:
    cfg = tomllib.loads(assembled)
    for inbound in cfg.get("inbounds", []):
        if inbound.get("type") == "socks5":
            _, port = inbound["listen"].rsplit(":", 1)
            return int(port)
    raise RuntimeError("no socks5 inbound in assembled config")


# ---------------------------------------------------------------------------
# Self-loopback: anywhere talking to itself (server + client on the device).
# server.toml is the server template (##test inbound## placeholder),
# inbounds.toml the inbound pool — same split as the client side.
# ---------------------------------------------------------------------------

SELF_CERT = "self-cert.pem"
SELF_KEY = "self-key.pem"


def gen_self_cert(run_dir: Path) -> None:
    out = run_dir / SELF_CERT
    if out.exists() and (run_dir / SELF_KEY).exists():
        return
    r = subprocess.run(
        ["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes",
         "-subj", "/CN=localhost", "-days", "2",
         "-keyout", str(run_dir / SELF_KEY), "-out", str(out)],
        capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"openssl cert generation failed: {r.stderr.strip()}")


def gen_x25519_pair() -> tuple[str, str]:
    """base64url private/public key pair for the reality inbound
    (same recipe as anywhere/config/vless-reality-server.toml)."""
    def b64url_tail(pem: str, pub: bool) -> str:
        der = subprocess.run(
            ["openssl", "pkey", "-in", "/dev/stdin",
             *(["-pubout"] if pub else []), "-outform", "DER"],
            input=pem.encode(), capture_output=True)  # DER is binary
        if der.returncode != 0:
            raise SystemExit(f"openssl pkey failed: {der.stderr.decode().strip()}")
        raw = base64.b64encode(der.stdout[-32:]).decode().rstrip("=")
        return raw.replace("+", "-").replace("/", "_")

    key = subprocess.run(
        ["openssl", "genpkey", "-algorithm", "X25519"],
        capture_output=True, text=True)
    if key.returncode != 0:
        raise SystemExit(f"openssl genpkey failed: {key.stderr.strip()}")
    pem = key.stdout
    return b64url_tail(pem, pub=False), b64url_tail(pem, pub=True)


def load_inbound_pool(cfgdir: Path) -> list[dict]:
    """Split inbounds.toml text on [[inbounds]] boundaries; each block is
    re-parsed standalone (sub-tables like [inbounds.transport] must follow
    their parent block)."""
    text = (cfgdir / "inbounds.toml").read_text()
    if not text.strip():
        return []
    blocks = re.split(r"(?m)^\[\[inbounds\]\]\s*$", text)[1:]
    out = []
    for i, b in enumerate(blocks):
        d = tomllib.loads("[[inbounds]]\n" + b)
        out.append(d["inbounds"][0])
    return out


def self_tag(inbound: dict) -> str:
    t = inbound["type"]
    tr = (inbound.get("transport") or {}).get("type")
    if inbound.get("reality"):
        return "self:vless-reality"
    if tr:
        return f"self:{t}-{tr}"
    return f"self:{t}"


def paired_outbound(inbound: dict, uuid: str, reality_pub: str | None) -> dict:
    """Client outbound matching the inbound under test."""
    listen = inbound["listen"]
    host, port = listen.rsplit(":", 1)
    ob: dict = {"type": inbound["type"], "tag": TEST_TAG,
                "server": f"{host}:{port}", "password": uuid}
    if inbound["type"] == "shadowsocks":
        # ss auth is method+psk, not the users UUID; 2022 ciphers need a
        # base64 PSK of the key length (16 for aes-128, else 32)
        method = inbound.get("method", "")
        if method.startswith("2022"):
            n = 16 if "128" in method else 32
            ob["password"] = base64.b64encode(secrets.token_bytes(n)).decode()
        for k in ("method", "plugin", "plugin_opts"):
            if inbound.get(k):
                ob[k] = inbound[k]
        return ob
    if inbound["type"] == "mless":
        ob["tls_fragment"] = False  # loopback: fragmentation only adds noise
    reality = inbound.get("reality")
    if reality:
        ob["sni"] = reality["server_names"][0]
        ob["flow"] = "xtls-rprx-vision"
        ob["reality"] = {"public_key": reality_pub,
                         "short_id": (reality.get("short_ids") or [""])[0]}
        return ob
    ob["sni"] = "localhost"
    ob["insecure"] = True
    tr = inbound.get("transport")
    if tr:
        ob["transport"] = copy.deepcopy(tr)
    return ob


def assemble_self(server_tpl: dict, client_tpl: dict, inbound: dict,
                  uuid: str) -> tuple[str, str, str]:
    """Assemble (server_text, client_text, self tag) for one inbound.
    Both round-trip checked like assemble()."""
    tag = self_tag(inbound)
    reality_pub = None
    srv = copy.deepcopy(server_tpl)
    srv.setdefault("users", [{"name": "self"}])[0]["password"] = uuid
    if inbound.get("reality"):
        priv, reality_pub = gen_x25519_pair()
        srv_in = copy.deepcopy(inbound)
        srv_in["reality"]["private_key"] = priv
    else:
        srv_in = copy.deepcopy(inbound)
        if srv_in.get("cert") == "cert.pem":
            srv_in["cert"] = SELF_CERT
        if srv_in.get("key") == "key.pem":
            srv_in["key"] = SELF_KEY
    srv.setdefault("inbounds", []).append(srv_in)

    cli = copy.deepcopy(client_tpl)
    cli.setdefault("outbounds", []).insert(0, paired_outbound(inbound, uuid, reality_pub))

    server_text, client_text = toml_dumps(srv), toml_dumps(cli)
    if tomllib.loads(server_text) != srv:
        raise RuntimeError(f"toml round-trip mismatch (server, {tag})")
    if tomllib.loads(client_text) != cli:
        raise RuntimeError(f"toml round-trip mismatch (client, {tag})")
    return server_text, client_text, tag


