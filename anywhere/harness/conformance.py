"""anywhere conformance harness.

Drives real `anywhere` binaries on real machines through their production
node list, one node at a time, and produces an HTML matrix report.

Config directory (passed via -c), nothing in it is generated by this script:

  config.toml      common template. Contains the literal placeholder line
                   `##test node##` where the node under test is injected.
  <platform>.toml  optional per-platform override, deep-merged over the
                   template (tables merge, arrays and scalars replace).
                   Absent or empty file -> template used as-is.
  outbounds.toml   node pool. Nodes are injected one at a time with their
                   tag forced to "test" (the template's urltest group
                   references that tag).
  test.toml        [test] run parameters + per-platform transport sections
                   ([mac] file = path, [windows] ssh = host,
                   [android] adb = serial ("" -> the single device),
                   arch = x64|arm64 where the releases artifact is ambiguous).

Usage:
  python3 conformance.py -c ~/anywhere-test -r ~/quiche/releases
  python3 conformance.py -c ~/anywhere-test --platform mac --node yt
  python3 conformance.py -c ~/anywhere-test --platform windows-x64,android-armv7
  python3 conformance.py -c ~/anywhere-test --count 6
  python3 conformance.py -c ~/anywhere-test --dry-run

The HTML report is written next to the config directory; per-run artifacts
(final configs, client logs, results.json) land in <config-dir>/run/<ts>/.
"""

