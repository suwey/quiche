# common spellings accepted in test.toml / --platform <p>-<arch>
ARCH_ALIASES = {"aarch64": "arm64", "x86_64": "x64", "amd64": "x64"}


def resolve_arch(platform: str, section: dict,
                 override: str | None) -> tuple[str | None, str | None]:
    """CLI --platform <p>-<arch> wins over [platform] arch in test.toml;
    a declared arch that differs from the CLI one is a conflict, and a
    platform with several known arches needs one of the two. Returns
    (arch, problem)."""
    arch_keys = RELEASE_ARTIFACT_KEY.get(platform, {})
    toml_arch = section.get("arch")
    toml_arch = ARCH_ALIASES.get(toml_arch, toml_arch) if toml_arch else None
    override = ARCH_ALIASES.get(override, override) if override else None
    if override and toml_arch and override != toml_arch:
        return None, (f"[{platform}] arch conflict: --platform {platform}-{override} "
                      f"but test.toml has [{platform}] arch = {toml_arch}")
    arch = override or toml_arch
    if arch is None:
        if len(arch_keys) == 1:
            return next(iter(arch_keys)), None
        return None, (f"[{platform}] arch ambiguous ({', '.join(arch_keys)}); "
                      f"set [{platform}] arch in test.toml or use "
                      f"--platform {platform}-<arch>")
    if arch not in arch_keys:
        return None, (f"[{platform}] unknown arch {arch!r} "
                      f"(known: {', '.join(arch_keys)}; aliases: "
                      f"{', '.join(ARCH_ALIASES)})")
    return arch, None


def resolve_binary(platform: str, section: dict, releases: Path | None,
                   run_dir: Path, arch: str | None) -> tuple[Path | None, str | None]:
    """Returns (binary path or None, problem description or None)."""
    if section.get("file"):
        p = Path(section["file"]).expanduser()
        if not p.exists():
            return None, f"[{platform}] file= {p} does not exist"
        return p, None
    if releases is None:
        return None, f"[{platform}] no file= set and no -r releases dir given"
    key = RELEASE_ARTIFACT_KEY.get(platform, {}).get(arch)
    if key is None:
        return None, f"[{platform}] no release artifact mapping for arch={arch!r}"
    artifacts = sorted(releases.glob(f"anywhere-v*-{key}.tgz"))
    if not artifacts:
        return None, f"[{platform}] no anywhere-v*-{key}.tgz in {releases}"
    artifact = max(artifacts, key=lambda p: p.stat().st_mtime)  # newest build
    dest = run_dir / f"bin-{platform}"
    dest.mkdir(exist_ok=True)
    with tarfile.open(artifact) as tf:
        tf.extractall(dest, filter="data")
    found = sorted(p for p in dest.rglob("anywhere*") if p.is_file())
    if not found:
        return None, f"[{platform}] {artifact.name} contains no binary"
    return found[0], None


def stage_binary_tgz(platform: str, binary: Path, run_dir: Path) -> Path:
    """All remote distribution goes as a compressed package: repack the
    resolved binary (a releases tgz member or a raw file= binary) into a
    flat tgz whose root is the exe name, so remote extraction always lands
    the predictable path <deploy_dir>/<exe>."""
    exe = "anywhere.exe" if platform == "windows" else "anywhere"
    out = run_dir / f"bin-{platform}.tgz"
    with tarfile.open(out, "w:gz") as tf:
        tf.add(binary, arcname=exe)
    return out


