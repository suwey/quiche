def site_label(url: str) -> str:
    return urlparse(url).netloc.removeprefix("www.")


def curl_once(port: int, url: str, connect_timeout: int, max_time: int) -> tuple[bool, int | None, float | None, str | None]:
    """One request through socks5h (DNS goes through the proxy too).
    Returns (ok, http_code, latency_s, error)."""
    cmd = [
        "curl", "-x", f"socks5h://127.0.0.1:{port}",
        "--connect-timeout", str(connect_timeout),
        "-m", str(max_time),
        "-sS", "-o", "/dev/null",
        "-w", "%{http_code} %{time_total}",
        url,
    ]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=max_time + 5)
    except subprocess.TimeoutExpired:
        return False, None, None, "curl timed out"
    if r.returncode != 0:
        err = (r.stderr or "").strip().splitlines()
        return False, None, None, err[-1] if err else f"curl exit {r.returncode}"
    try:
        code_s, time_s = r.stdout.split()
        code, lat = int(code_s), float(time_s)
    except ValueError:
        return False, None, None, f"unparseable curl output: {r.stdout!r}"
    return 200 <= code < 400, code, lat, None


@dataclass
class SiteStats:
    url: str
    ok: int = 0
    total: int = 0
    latencies: list[float] = field(default_factory=list)
    series: list[tuple[bool, float | None]] = field(default_factory=list)
    error: str | None = None

    def passed(self, ratio: float) -> bool:
        return self.ok >= 1 and self.ok / self.total >= ratio

    def summary(self) -> dict:
        lats = self.latencies
        return {
            "url": self.url,
            "ok": self.ok,
            "total": self.total,
            "pass": None,  # filled by caller (needs pass_ratio)
            "min_ms": round(min(lats) * 1000) if lats else None,
            "p50_ms": round(statistics.median(lats) * 1000) if lats else None,
            "max_ms": round(max(lats) * 1000) if lats else None,
            "series": [[ok, round(ms * 1000) if ms else None] for ok, ms in self.series],
            "error": self.error,
        }


@dataclass
class NodeResult:
    tag: str
    type: str
    server: str | None
    first_ms: int | None = None
    pass_: bool | None = None
    sites: list[SiteStats] = field(default_factory=list)
    error: str | None = None
    skipped: bool = False

    def summary(self, ratio: float) -> dict:
        return {
            "tag": self.tag,
            "type": self.type,
            "server": self.server,
            "pass": self.pass_,
            "first_ms": self.first_ms,
            "skipped": self.skipped,
            "error": self.error,
            "sites": [s.summary() | {"pass": s.passed(ratio)} for s in self.sites],
        }


def test_node(runner, node: dict, template: dict, params: dict,
              run_dir: Path) -> NodeResult:
    """Full cycle for one node: assemble -> run client -> sample -> stop."""
    tag = node.get("tag", "unnamed")
    res = NodeResult(tag=tag, type=node["type"], server=node.get("server"))
    if node["type"] in NON_TESTABLE_TYPES:
        res.skipped = True
        return res

    text, _ = assemble(template, node)
    port, proc, log_path = runner.start(text, tag)

    connect_timeout = params["connect_timeout_s"]
    probe_timeout = params["probe_timeout_s"]
    sites: list[SiteStats] = [SiteStats(url=u) for u in params["sites"]]
    res.sites = sites

    try:
        err = runner.wait_ready(port, proc, log_path)
        if err:
            res.error = err
            return res

        # Warmup: one request carrying the full handshake. Retried until a
        # deadline so slow client startup (device, remote ssh) is absorbed;
        # a node that cannot complete it fails fast instead of burning the
        # whole probe phase on timeouts.
        deadline = time.monotonic() + 20
        while True:
            ok, code, lat, werr = curl_once(port, sites[0].url, connect_timeout, probe_timeout)
            if ok:
                res.first_ms = round(lat * 1000)
                break
            sites[0].error = werr or f"http {code}"
            if time.monotonic() > deadline:
                res.error = f"warmup failed: {sites[0].error}"
                return res
            time.sleep(0.5)

        # Fixed-count or fixed-duration sampling; warmup already carried the
        # first full handshake.
        err = run_probes(port, sites, params, poll_proc=proc.poll)
        if err:
            res.error = err
        return res
    finally:
        runner.stop(proc)


def wait_port(port: int, timeout: float) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=0.5):
                return True
        except OSError:
            time.sleep(0.2)
    return False


# ---------------------------------------------------------------------------
# Runners: how the client is launched and how its socks5 port is reached.
# Every runner returns the host-side port curl should hit (local bind or
# forwarded), so the sampling code is transport-agnostic.
# ---------------------------------------------------------------------------

def _popen_logged(cmd: list[str], log_path: Path) -> subprocess.Popen:
    return subprocess.Popen(cmd, stdout=open(log_path, "wb"), stderr=subprocess.STDOUT)


def _stop_proc(proc: subprocess.Popen) -> None:
    proc.terminate()
    try:
        proc.wait(timeout=3)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait()


class LocalRunner:
    """Client as a local subprocess; curl hits the local socks port (mac)."""

    def __init__(self, binary: Path, run_dir: Path):
        self.binary = binary
        self.run_dir = run_dir
        self.bg_proc: subprocess.Popen | None = None

    def setup(self) -> None:
        pass

    def start_bg(self, cfg_text: str, name: str) -> str | None:
        """Long-lived background process (self-loop server). Returns an
        error string on early exit."""
        cfg_path = self.run_dir / f"{name}.toml"
        cfg_path.write_text(cfg_text)
        log_path = self.run_dir / f"{name}.log"
        self.bg_proc = _popen_logged([str(self.binary), "-c", str(cfg_path)],
                                     log_path)
        time.sleep(1.0)
        if self.bg_proc.poll() is not None:
            return f"{name} exited early (code {self.bg_proc.returncode}), see {log_path.name}"
        return None

    def start(self, cfg_text: str, tag: str) -> tuple[int, subprocess.Popen, Path]:
        cfg_path = self.run_dir / f"final-{tag}.toml"
        cfg_path.write_text(cfg_text)
        log_path = self.run_dir / f"client-{tag}.log"
        proc = _popen_logged([str(self.binary), "-c", str(cfg_path)], log_path)
        return socks_port(cfg_text), proc, log_path

    def wait_ready(self, port: int, proc: subprocess.Popen,
                   log_path: Path) -> str | None:
        if proc.poll() is not None:
            return f"client exited early (code {proc.returncode}), see {log_path.name}"
        if not wait_port(port, timeout=15):
            return f"socks5 :{port} never came up, see {log_path.name}"
        return None

    def stop(self, proc: subprocess.Popen) -> None:
        # stop only this node's session; a self-loop server (bg_proc) and
        # other concurrently-running processes must survive
        _stop_proc(proc)

    def cleanup(self) -> None:
        if self.bg_proc is not None:
            _stop_proc(self.bg_proc)
            self.bg_proc = None


class AdbRunner:
    """Client as a raw executable on an Android device under adb shell
    (shell uid: no root, no UI automation). The device socks port is pulled
    back to the host with `adb forward` and driven by host-side curl, since
    Android ships no usable curl on-device."""

    def __init__(self, bin_tgz: Path, run_dir: Path,
                 serial: str | None = None,
                 device_dir: str = "/data/local/tmp/anywhere-test",
                 forward_port: int = 11080):
        self.bin_tgz = bin_tgz
        self.run_dir = run_dir
        self.serial_arg = serial  # None -> auto-pick the single device
        self.device_dir = device_dir
        self.forward_port = forward_port
        self.serial: str | None = None

    def _adb(self, *args: str, timeout: int = 60, check: bool = True) -> str:
        cmd = ["adb"] + (["-s", self.serial] if self.serial else []) + list(args)
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        if check and r.returncode != 0:
            raise RuntimeError(f"adb {' '.join(args)}: {(r.stderr or r.stdout).strip()}")
        return r.stdout

    def _pkill_stale(self) -> None:
        # The [a] bracket keeps the pattern from matching the very shell that
        # runs it (its cmdline contains the literal pattern text).
        self._adb("shell",
                  f"pkill -f {self.device_dir}/[a]nywhere 2>/dev/null; true",
                  check=False)

    def setup(self) -> None:
        self.serial = _adb_pick_serial(self.serial_arg)
        # stale forward from a crashed previous run would fail the bind below
        subprocess.run(["adb", "-s", self.serial, "forward", "--remove",
                        f"tcp:{self.forward_port}"], capture_output=True)
        self._adb("shell", f"mkdir -p {self.device_dir}")
        self._pkill_stale()
        self._adb("push", str(self.bin_tgz), f"{self.device_dir}/bin.tgz", timeout=300)
        self._adb("shell", f"cd {self.device_dir} && tar -xzf bin.tgz && "
                           f"chmod 755 anywhere && rm -f bin.tgz")

    def start(self, cfg_text: str, tag: str) -> tuple[int, subprocess.Popen, Path]:
        cfg_path = self.run_dir / f"final-{tag}.toml"
        cfg_path.write_text(cfg_text)
        device_cfg = f"{self.device_dir}/final-{tag}.toml"
        self._adb("push", str(cfg_path), device_cfg)
        device_port = socks_port(cfg_text)
        self._adb("forward", f"tcp:{self.forward_port}", f"tcp:{device_port}")
        log_path = self.run_dir / f"client-{tag}.log"
        proc = _popen_logged(
            ["adb", "-s", self.serial, "shell",
             f"{self.device_dir}/anywhere -c {device_cfg}"], log_path)
        return self.forward_port, proc, log_path

    def start_bg(self, cfg_text: str, name: str) -> str | None:
        cfg_path = self.run_dir / f"{name}.toml"
        cfg_path.write_text(cfg_text)
        device_cfg = f"{self.device_dir}/{name}.toml"
        self._adb("push", str(cfg_path), device_cfg)
        log_path = self.run_dir / f"{name}.log"
        self.bg_proc = _popen_logged(
            ["adb", "-s", self.serial, "shell",
             f"{self.device_dir}/anywhere -c {device_cfg}"], log_path)
        time.sleep(1.5)
        if self.bg_proc.poll() is not None:
            return f"{name} exited early (code {self.bg_proc.returncode}), see {log_path.name}"
        return None

    def wait_ready(self, port: int, proc: subprocess.Popen,
                   log_path: Path) -> str | None:
        if proc.poll() is not None:
            return f"client exited early (code {proc.returncode}), see {log_path.name} " \
                   f"(exec denied? SELinux? check device)"
        # adb forwards accept before the device side listens; the warmup
        # retry loop absorbs client startup latency.
        return None

    def stop(self, proc: subprocess.Popen) -> None:
        # session kill only — never the device-wide pkill: a self-loop
        # server running next to this client must survive
        _stop_proc(proc)

    def cleanup(self) -> None:
        if self.bg_proc is not None:
            _stop_proc(self.bg_proc)
            self.bg_proc = None
        self._pkill_stale()
        if self.serial:
            subprocess.run(["adb", "-s", self.serial, "forward", "--remove",
                            f"tcp:{self.forward_port}"], capture_output=True)


def _adb_online_serials() -> list[str]:
    r = subprocess.run(["adb", "devices"], capture_output=True, text=True, timeout=15)
    return [line.split("\t")[0] for line in r.stdout.splitlines()[1:]
            if line.endswith("\tdevice")]


class SshRunner:
    """Client on a remote host over passwordless ssh (windows/linux).

    Deploy directory = the parent of the [ui] serve_path configured in the
    platform override file (windows.toml: serve_path = "D:/rust/ui" ->
    deploy to D:/rust/), so binary, final-<tag>.toml and ui/ land next to
    the real deployment. The client runs in the foreground of the same ssh
    session that carries its own `ssh -L` tunnel; killing the session stops
    the client.
    """

    def __init__(self, platform: str, bin_tgz: Path, run_dir: Path, dest: str,
                 serve_path: str, forward_port: int = 11081,
                 ui_tgz: Path | None = None):
        self.platform = platform
        self.windows = platform == "windows"
        self.bin_tgz = bin_tgz
        self.run_dir = run_dir
        self.dest = dest
        self.serve_path = serve_path.rstrip("/")
        if "/" not in self.serve_path or not self.serve_path.rsplit("/", 1)[0]:
            raise SystemExit(f"[{platform}] serve_path {serve_path!r} must be "
                             f"<dir>/ui (the deploy dir is its parent)")
        if any(bad in self.serve_path for bad in ("..", "*", "?", "\\", "//")):
            raise SystemExit(f"[{platform}] serve_path {serve_path!r} contains "
                             f" '..', wildcards or doubled slashes — not allowed "
                             f"(deletion below is scoped to this path)")
        if self.serve_path.rsplit("/", 1)[1] != "ui":
            raise SystemExit(f"[{platform}] serve_path {serve_path!r} must end in "
                             f"/ui — that is the pushed artifact dir name")
        self.remote_dir = self.serve_path.rsplit("/", 1)[0]
        self.exe = "anywhere.exe" if self.windows else "anywhere"
        self.forward_port = forward_port
        self.ui_tgz = ui_tgz
        self.bg_proc: subprocess.Popen | None = None
        self.bg_name: str | None = None

    # Harness-scoped ssh options: no known_hosts (the same LAN box dual-boots
    # windows/linux, so its host key legitimately flaps), no password prompt.
    SSH_OPTS = ["-o", "UserKnownHostsFile=/dev/null", "-o",
                "StrictHostKeyChecking=no", "-o", "BatchMode=yes",
                "-o", "ConnectTimeout=8"]

    def _ssh(self, *args: str, check: bool = True, timeout: int = 60) -> str:
        cmd = ["ssh", *self.SSH_OPTS, self.dest, *args]
        r = subprocess.run(cmd, capture_output=True, text=True, errors="replace",
                           timeout=timeout)
        if check and r.returncode != 0:
            raise RuntimeError(f"ssh {self.dest} {' '.join(args)!r}: "
                               f"{(r.stderr or r.stdout).strip()}")
        return r.stdout

    def _scp(self, src: Path, dest_path: str, timeout: int = 300,
             recursive: bool = False) -> None:
        cmd = ["scp", *self.SSH_OPTS]
        if recursive:
            cmd.append("-r")
        cmd += [str(src), f"{self.dest}:{dest_path}"]
        last = None
        for attempt in (1, 2):  # one retry: flaky wifi drops otherwise abort the run
            r = subprocess.run(cmd, capture_output=True, text=True,
                               errors="replace", timeout=timeout)
            if r.returncode == 0:
                return
            last = RuntimeError(f"scp {src} -> {dest_path}: "
                                f"{(r.stderr or r.stdout).strip()}")
            time.sleep(1)
        raise last

    def _kill_stale(self) -> None:
        exe = f"{self.remote_dir}/{self.exe}"
        if self.windows:
            # kill by exact path: a real anywhere.exe elsewhere on the box
            # must survive the test run
            ps = (f"Get-Process anywhere -ErrorAction SilentlyContinue | "
                  f"Where-Object {{ $_.Path -eq '{exe.replace('/', chr(92))}' }} | "
                  f"Stop-Process -Force")
            self._ssh(f'powershell -NoProfile -Command "{ps}"', check=False)
        else:
            self._ssh(f"pkill -f {self.remote_dir}/[a]nywhere 2>/dev/null; true",
                      check=False)

    def _probe_deploy_dir(self) -> None:
        """The deploy dir is the user's real deployment location: it must
        already exist. Never mkdir it — a typo'd serve_path (e.g. /Home vs
        /home) would otherwise silently spawn a bogus tree."""
        if self.windows:
            cmd = f'if not exist "{self.remote_dir.replace("/", chr(92))}\\" exit /b 1'
        else:
            cmd = f'test -d "{self.remote_dir}"'
        r = subprocess.run(["ssh", *self.SSH_OPTS, self.dest, cmd],
                           capture_output=True, text=True, errors="replace",
                           timeout=30)
        if r.returncode != 0:
            raise SystemExit(
                f"[{self.platform}] deploy dir {self.remote_dir!r} does not exist "
                f"on {self.dest} — fix serve_path in the platform override file "
                f"or deploy anywhere there first (the harness never creates it)")

    def _rm_remote_ui(self) -> None:
        """Strict mirror push: delete the remote ui dir before re-pushing it.
        The target is exactly <remote_dir>/ui — serve_path is validated in
        __init__ (must end in /ui, no '..'/wildcards), so nothing else on the
        box can ever be matched."""
        target = f"{self.remote_dir}/ui"
        assert target == self.serve_path
        if self.windows:
            p = target.replace("/", chr(92))
            self._ssh(f'if exist "{p}\\" rmdir /s /q "{p}"')
        else:
            self._ssh(f'rm -rf "{target}"')

    def setup(self) -> None:
        self._probe_deploy_dir()
        # kill any stale client first: windows locks running executables,
        # which would make the scp overwrite below fail
        self._kill_stale()
        self._scp(self.bin_tgz, f"{self.remote_dir}/bin.tgz")
        if self.windows:
            p = self.remote_dir.replace("/", chr(92))
            self._ssh(f'tar -xzf "{p}\\bin.tgz" -C "{p}" & del "{p}\\bin.tgz"')
        else:
            self._ssh(f"tar -xzf {self.remote_dir}/bin.tgz -C {self.remote_dir} "
                      f"&& rm -f {self.remote_dir}/bin.tgz "
                      f"&& chmod 755 {self.remote_dir}/{self.exe}")
        if self.ui_tgz is not None:
            # strict mirror via one-file transfer: rm remote ui, push the
            # tgz, extract remotely (163 small scp files drop on flaky wifi)
            self._rm_remote_ui()
            self._scp(self.ui_tgz, f"{self.remote_dir}/ui.tgz")
            if self.windows:
                p = self.remote_dir.replace("/", chr(92))
                self._ssh(f'tar -xzf "{p}\\ui.tgz" -C "{p}" & del "{p}\\ui.tgz"')
            else:
                self._ssh(f"tar -xzf {self.remote_dir}/ui.tgz -C {self.remote_dir} "
                          f"&& rm -f {self.remote_dir}/ui.tgz")

    def _deploy_text(self, cfg_text: str, tag: str) -> str:
        # the merged config already carries the platform's serve_path, which
        # points at <remote_dir>/ui by construction — nothing to rewrite
        local = self.run_dir / f"final-{tag}.toml"
        local.write_text(cfg_text)
        self._scp(local, f"{self.remote_dir}/final-{tag}.toml")
        return cfg_text

    def start(self, cfg_text: str, tag: str) -> tuple[int, subprocess.Popen, Path]:
        text = self._deploy_text(cfg_text, tag)
        device_port = socks_port(text)
        cfg_remote = f"{self.remote_dir}/final-{tag}.toml"
        if self.windows:
            remote_cmd = f'"{self.remote_dir}/{self.exe}" -c "{cfg_remote}"'
        else:
            remote_cmd = f"{self.remote_dir}/{self.exe} -c {cfg_remote}"
        log_path = self.run_dir / f"client-{tag}.log"
        proc = subprocess.Popen(
            ["ssh", *self.SSH_OPTS, "-o", "ExitOnForwardFailure=yes",
             "-L", f"127.0.0.1:{self.forward_port}:127.0.0.1:{device_port}",
             self.dest, remote_cmd],
            stdin=subprocess.DEVNULL, stdout=open(log_path, "wb"),
            stderr=subprocess.STDOUT)
        return self.forward_port, proc, log_path

    def start_bg(self, cfg_text: str, name: str) -> str | None:
        """Self-loop server: its own forward-free ssh session, long-lived."""
        local = self.run_dir / f"{name}.toml"
        local.write_text(cfg_text)
        self._scp(local, f"{self.remote_dir}/{name}.toml")
        # server-side cert files referenced by the config
        for f in (SELF_CERT, SELF_KEY):
            p = self.run_dir / f
            if p.exists():
                self._scp(p, f"{self.remote_dir}/{f}")
        cfg_remote = f"{self.remote_dir}/{name}.toml"
        if self.windows:
            remote_cmd = f'"{self.remote_dir}/{self.exe}" -c "{cfg_remote}"'
        else:
            remote_cmd = f"{self.remote_dir}/{self.exe} -c {cfg_remote}"
        log_path = self.run_dir / f"{name}.log"
        self.bg_proc = subprocess.Popen(
            ["ssh", *self.SSH_OPTS, self.dest, remote_cmd],
            stdin=subprocess.DEVNULL, stdout=open(log_path, "wb"),
            stderr=subprocess.STDOUT)
        time.sleep(1.5)
        if self.bg_proc.poll() is not None:
            return f"{name} exited early (code {self.bg_proc.returncode}), see {log_path.name}"
        self.bg_name = name
        return None

    def wait_ready(self, port: int, proc: subprocess.Popen,
                   log_path: Path) -> str | None:
        if proc.poll() is not None:
            return f"ssh session exited early (code {proc.returncode}), see {log_path.name}"
        return None  # warmup retry loop absorbs remote startup latency

    def stop(self, proc: subprocess.Popen) -> None:
        # kill only this node's tunnel+client session; the self-loop server
        # runs in its own session and must survive
        _stop_proc(proc)

    def cleanup(self) -> None:
        if self.bg_proc is not None:
            _stop_proc(self.bg_proc)
            self.bg_proc = None
        self._kill_stale()


def _adb_pick_serial(wanted: str | None = None) -> str:
    online = _adb_online_serials()
    if not online and wanted and (":" in wanted or wanted.count(".") == 3):
        # network adb shorthand: connect first, then re-scan
        subprocess.run(["adb", "connect", wanted], capture_output=True, timeout=30)
        online = _adb_online_serials()
    if not online:
        raise SystemExit("no adb device in 'device' state (run: adb devices)")
    if wanted and wanted in online:
        return wanted
    prefixed = [s for s in online if wanted and s.startswith(wanted)]
    if len(prefixed) == 1:
        return prefixed[0]  # e.g. wanted=ip matches serial ip:port
    if len(online) == 1:
        print(f"[android] note: serial {wanted!r} not connected verbatim, "
              f"using the single online device {online[0]!r}")
        return online[0]
    raise SystemExit(f"serial {wanted!r} not online; connected: {online}; "
                     "set [android] adb = <exact serial> or empty for auto")


def make_runner(platform: str, section: dict, binary: Path, run_dir: Path,
                bin_tgz: Path | None = None, ui_tgz: Path | None = None,
                serve_path: str | None = None):
    if platform == "mac":
        return LocalRunner(binary, run_dir)
    if platform == "android":
        return AdbRunner(bin_tgz, run_dir,
                         serial=section.get("adb") or None,
                         device_dir=section.get("device_dir")
                         or "/data/local/tmp/anywhere-test",
                         forward_port=section.get("forward_port") or 11080)
    if platform in ("windows", "linux"):
        dest = section.get("ssh")
        if not dest:
            raise SystemExit(f"[{platform}] ssh = user@host is not set in test.toml")
        if not serve_path:
            raise SystemExit(f"[{platform}] no [ui] serve_path configured — add it to "
                             f"{platform}.toml (e.g. serve_path = \"D:/rust/ui\"); "
                             f"the deploy dir is its parent")
        return SshRunner(platform, bin_tgz, run_dir, dest=dest,
                         serve_path=serve_path,
                         forward_port=section.get("forward_port") or 11081,
                         ui_tgz=ui_tgz)
    raise SystemExit(f"no runner implemented for platform {platform!r}")


def resolve_ui_tgz(releases: Path | None) -> Path | None:
    """Newest releases ui artifact. Pushed as one file and extracted on the
    remote host — scp-ing 163 small files individually drops on flaky wifi."""
    if releases is None:
        return None
    tgzs = list(releases.glob("anywhere-v*-ui.tgz"))
    if not tgzs:
        return None
    return max(tgzs, key=lambda p: p.stat().st_mtime)


